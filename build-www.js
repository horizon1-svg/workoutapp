#!/usr/bin/env node
/* Generates www/ (the folder Capacitor packages into the APK) from the web-app source files.
   The source files are never modified; everything Android-specific happens on the copies in www/.
     node build-www.js                          -> ./www   (strict: fonts and Capacitor runtime must be installed)
     node build-www.js --out DIR                -> write somewhere else
     node build-www.js --allow-missing-fonts    -> tests only (no node_modules available)
   What it does:
     1. copies index.html, style.css, app.js, data.js, icons.js (+ native-bridge.js)
     2. removes the Google Fonts links and bundles Sora + Cairo locally (from the @fontsource npm packages, OFL licence)
     3. makes the safe-area CSS use Capacitor's --safe-area-inset-* variables, falling back to env()
     4. copies the Capacitor JS runtime and injects it + the bridge after app.js
     5. fails if anything in www/ would still need the internet                                                        */
'use strict';
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const arg = (n, d) => { const i = args.indexOf(n); return i >= 0 && args[i + 1] ? args[i + 1] : d; };
const SRC = __dirname;
const OUT = path.resolve(arg('--out', path.join(SRC, 'www')));
const LENIENT = flag('--allow-missing-fonts');
const APP_FILES = ['style.css', 'app.js', 'data.js', 'icons.js'];
const FONT_SPECS = [
  { pkg: 'sora', family: 'Sora', weights: [400, 500, 600, 700, 800], subsets: ['latin'] },
  { pkg: 'cairo', family: 'Cairo', weights: [600, 700, 800, 900], subsets: ['arabic', 'latin'] },
];

function fail(msg) { console.error('\nBUILD-WWW ERROR: ' + msg + '\n'); process.exit(1); }
function warn(msg) { console.warn('warning: ' + msg); }
const read = (p) => fs.readFileSync(p, 'utf8');

// ---- safety checks ----
if (OUT === SRC || SRC.indexOf(OUT + path.sep) === 0) fail('--out must not be the project folder itself: ' + OUT);
['index.html', 'native-bridge.js'].concat(APP_FILES).forEach((f) => { if (!fs.existsSync(path.join(SRC, f))) fail('Missing source file: ' + f); });
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });

// ---- 1. fonts: Sora + Cairo bundled locally ----
const problems = [];
let fontCss = '/* Sora + Cairo, bundled locally (SIL Open Font License). Generated by build-www.js. */\n';
let faceCount = 0;
const copied = new Set();
FONT_SPECS.forEach((spec) => {
  const pkgDir = path.join(SRC, 'node_modules', '@fontsource', spec.pkg);
  spec.weights.forEach((w) => {
    const cssFile = path.join(pkgDir, w + '.css');
    if (!fs.existsSync(cssFile)) { problems.push(spec.family + ' ' + w + ': ' + path.relative(SRC, cssFile) + ' not found'); return; }
    const faces = read(cssFile).match(/@font-face\s*\{[^}]*\}/g) || [];
    spec.subsets.forEach((subset) => {
      // pick the face by its .woff2 file name (e.g. sora-latin-400-normal.woff2), not by the CSS comment style
      const suffix = '-' + subset + '-' + w + '-normal.woff2';
      const block = faces.find((b) => { const f = b.match(/url\(\s*['"]?[^)'"]*?([^/)'"]+\.woff2)['"]?\s*\)/); return f && f[1].endsWith(suffix); });
      if (!block) { problems.push(spec.family + ' ' + w + ': no face ending in "' + suffix + '" in ' + path.basename(cssFile)); return; }
      const m = block.match(/url\(\s*['"]?\.?\/?(files\/[^)'"]+\.woff2)['"]?\s*\)/);
      if (!m) { problems.push(spec.family + ' ' + w + ' ' + subset + ': no .woff2 source in the CSS'); return; }
      const fileName = path.basename(m[1]);
      const from = path.join(pkgDir, m[1]);
      if (!fs.existsSync(from)) { problems.push(spec.family + ' ' + w + ' ' + subset + ': font file ' + fileName + ' missing'); return; }
      if (!copied.has(fileName)) { fs.copyFileSync(from, path.join(OUT, 'fonts', fileName)); copied.add(fileName); }
      const face = block.replace(/src:[^;]+;/, "src: url(fonts/" + fileName + ") format('woff2');");
      fontCss += '/* ' + spec.family + ' ' + w + ' ' + subset + ' */\n' + face + '\n';
      faceCount++;
    });
  });
});
if (problems.length) {
  if (!LENIENT) fail('Could not bundle the fonts (' + problems.length + ' problem(s)). Did "npm install" finish?\n  - ' + problems.slice(0, 8).join('\n  - '));
  warn('fonts not bundled (--allow-missing-fonts): ' + problems.length + ' item(s) missing');
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), fontCss);

// ---- 2. verbatim copies (checked afterwards) ----
APP_FILES.forEach((f) => fs.copyFileSync(path.join(SRC, f), path.join(OUT, f)));
fs.copyFileSync(path.join(SRC, 'native-bridge.js'), path.join(OUT, 'native-bridge.js'));

// ---- 3. safe-area CSS: prefer Capacitor's --safe-area-inset-*, fall back to env() ----
let css = read(path.join(OUT, 'style.css'));
let safeAreaUses = 0;
css = css.replace(/env\(\s*safe-area-inset-(top|bottom|left|right)\s*(?:,\s*0px\s*)?\)/g, (all, side) => { safeAreaUses++; return 'var(--safe-area-inset-' + side + ', env(safe-area-inset-' + side + ', 0px))'; });
fs.writeFileSync(path.join(OUT, 'style.css'), css);

// ---- 4. Capacitor JS runtime ----
const runtimeCandidates = ['dist/capacitor.js', 'dist/capacitor.min.js'].map((p) => path.join(SRC, 'node_modules', '@capacitor', 'core', p));
const runtime = runtimeCandidates.find((p) => fs.existsSync(p));
if (runtime) fs.copyFileSync(runtime, path.join(OUT, 'capacitor.js'));
else if (!LENIENT) fail('Capacitor runtime not found in node_modules/@capacitor/core/dist. Did "npm install" finish?');
else warn('Capacitor runtime missing (--allow-missing-fonts): the Android back-button bridge cannot attach in this build');

// ---- 5. index.html ----
let html = read(path.join(SRC, 'index.html'));
const before = html.length;
html = html.replace(/[ \t]*<link\b[^>]*fonts\.(?:googleapis|gstatic)\.com[^>]*>[ \t]*\r?\n?/g, '');
const removedFontLinks = before !== html.length;
const styleTag = /<link\b[^>]*href=["']style\.css["'][^>]*>/;
html = styleTag.test(html) ? html.replace(styleTag, (t) => '<link rel="stylesheet" href="fonts.css">\n  ' + t) : html.replace('</head>', '  <link rel="stylesheet" href="fonts.css">\n</head>');
const scripts = '\n  <script src="native-bridge.js"></script>' +
  (runtime ? '\n  <script src="capacitor.js"></script>' : '');
const appTag = /<script\b[^>]*src=["']app\.js["'][^>]*><\/script>/;
if (!appTag.test(html)) fail('index.html has no <script src="app.js"> tag, so the bridge cannot be added after it.');
html = html.replace(appTag, (t) => t + scripts);
fs.writeFileSync(path.join(OUT, 'index.html'), html);

// ---- 6. verification ----
['app.js', 'data.js', 'icons.js'].forEach((f) => { if (!fs.readFileSync(path.join(SRC, f)).equals(fs.readFileSync(path.join(OUT, f)))) fail(f + ' changed while copying'); });
['index.html', 'style.css', 'fonts.css'].forEach((f) => {
  const text = read(path.join(OUT, f)).replace(/\/\*[\s\S]*?\*\//g, '').replace(/<!--[\s\S]*?-->/g, ''); // comments are harmless
  const ext = text.match(/https?:\/\/[^\s"')]+/g);
  if (ext) fail(f + ' still references the internet: ' + ext.slice(0, 3).join(', ') + '\n  The packaged app must work offline.');
  if (/@import/.test(text)) fail(f + ' uses @import (a possible remote dependency).');
});
if (!removedFontLinks) warn('index.html had no Google Fonts links to remove (is this an older/newer index.html?)');
if (safeAreaUses === 0) warn('style.css contains no env(safe-area-inset-*) rules');

const size = (f) => Math.round(fs.statSync(path.join(OUT, f)).size / 1024) + ' KB';
console.log('www/ ready: ' + OUT);
console.log('  files: index.html ' + size('index.html') + ', style.css ' + size('style.css') + ', app.js ' + size('app.js') + ', data.js ' + size('data.js') + (runtime ? ', capacitor.js ' + size('capacitor.js') : ''));
console.log('  fonts: ' + faceCount + ' font faces, ' + copied.size + ' .woff2 files');
console.log('  safe-area rules rewritten: ' + safeAreaUses + ' | Google Fonts links removed: ' + (removedFontLinks ? 'yes' : 'no'));
