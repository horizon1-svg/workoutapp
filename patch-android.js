#!/usr/bin/env node
/* Applies WorkoutApp's settings to the Android project that "npx cap add android" generates.
     node patch-android.js debug|release
   Edits (all idempotent, run twice = same result):
     - AndroidManifest.xml: portrait only, app label taken from a Gradle placeholder
     - app/build.gradle:    version numbers, stable signing, ".debug" id + "WorkoutApp Debug" label for debug builds
   It fails loudly if the generated files do not look as expected, instead of silently skipping a setting. */
'use strict';
const fs = require('fs');
const path = require('path');

const REMOVE_INTERNET_PERMISSION = false; // Capacitor's template declares INTERNET. The app does not need it (it is fully offline);
                                          // set to true only after testing a build on the phone without it.
const variant = process.argv[2];
function die(msg) { console.error('\nPATCH-ANDROID ERROR: ' + msg + '\n'); process.exit(1); }
if (variant !== 'debug' && variant !== 'release') die('Usage: node patch-android.js debug|release');

const root = process.env.WA_PROJECT_DIR ? path.resolve(process.env.WA_PROJECT_DIR) : __dirname;
const appDir = path.join(root, 'android', 'app');
const manifestPath = path.join(appDir, 'src', 'main', 'AndroidManifest.xml');
const gradlePath = path.join(appDir, 'build.gradle');
if (!fs.existsSync(manifestPath)) die('android/app/src/main/AndroidManifest.xml not found. Run "npx cap add android" first.');
if (!fs.existsSync(gradlePath)) die(fs.existsSync(gradlePath + '.kts') ? 'The generated project uses build.gradle.kts, which this script does not handle yet.' : 'android/app/build.gradle not found. Run "npx cap add android" first.');

const cfgPath = path.join(root, 'capacitor.config.json');
const cfg = fs.existsSync(cfgPath) ? JSON.parse(fs.readFileSync(cfgPath, 'utf8')) : {};

// ---------- AndroidManifest.xml ----------
let manifest = fs.readFileSync(manifestPath, 'utf8');
const actMatch = manifest.match(/<activity\b[^>]*MainActivity[^>]*>/);
if (!actMatch) die('Could not find the MainActivity <activity> tag in AndroidManifest.xml (the Capacitor template may have changed).');
let act = actMatch[0];
if (/android:screenOrientation=/.test(act)) act = act.replace(/android:screenOrientation="[^"]*"/, 'android:screenOrientation="portrait"');
else act = act.replace('<activity', '<activity android:screenOrientation="portrait"');
manifest = manifest.replace(actMatch[0], act);
// The label comes from a placeholder so that debug and release builds can be told apart on the phone.
let labelsPatched = 0;
manifest = manifest.replace(/android:label="@string\/(?:app_name|title_activity_main)"/g, () => { labelsPatched++; return 'android:label="${appLabel}"'; });
if (!/\$\{appLabel\}/.test(manifest)) console.warn('warning: no android:label was replaced by ${appLabel}; debug and release will show the same name.');
if (REMOVE_INTERNET_PERMISSION) manifest = manifest.replace(/[ \t]*<uses-permission\b[^>]*android\.permission\.INTERNET[^>]*\/>[ \t]*\r?\n?/g, '');
fs.writeFileSync(manifestPath, manifest);

// ---------- app/build.gradle (Groovy) ----------
const MARK = '// >>> WorkoutApp overrides (generated by patch-android.js - do not edit by hand)';
let gradle = fs.readFileSync(gradlePath, 'utf8');
const at = gradle.indexOf(MARK);
if (at >= 0) gradle = gradle.slice(0, at).replace(/\s+$/, '') + '\n';
const label = cfg.appName || 'WorkoutApp';
gradle += `
${MARK}
// Values come from the build machine's environment (GitHub Actions). Nothing secret is written into this file.
def waVersionCode = (System.getenv('WA_VERSION_CODE') ?: '1').toInteger()
def waVersionName = System.getenv('WA_VERSION_NAME') ?: '1.0.0'
def waDebugKeystore = System.getenv('WA_DEBUG_KEYSTORE')      // public debug key kept in the repo, so debug updates install over each other
def waReleaseKeystore = System.getenv('WA_KEYSTORE_FILE')     // your private release key (decoded from GitHub secrets at build time)

android {
    defaultConfig {
        versionCode = waVersionCode
        versionName = waVersionName
    }
    signingConfigs {
        if (waDebugKeystore) {
            wadebug {
                storeFile = file(waDebugKeystore)
                storePassword = 'android'
                keyAlias = 'androiddebugkey'
                keyPassword = 'android'
            }
        }
        if (waReleaseKeystore) {
            warelease {
                storeFile = file(waReleaseKeystore)
                storePassword = System.getenv('ANDROID_KEYSTORE_PASSWORD')
                keyAlias = System.getenv('ANDROID_KEY_ALIAS')
                keyPassword = System.getenv('ANDROID_KEY_PASSWORD')
            }
        }
    }
    buildTypes {
        debug {
            applicationIdSuffix = '.debug'
            versionNameSuffix = '-debug'
            manifestPlaceholders = [appLabel: '${label} Debug']
            if (waDebugKeystore) { signingConfig = signingConfigs.wadebug }
        }
        release {
            manifestPlaceholders = [appLabel: '${label}']
            if (waReleaseKeystore) { signingConfig = signingConfigs.warelease }
        }
    }
}
`;
fs.writeFileSync(gradlePath, gradle);

console.log('patch-android (' + variant + '): portrait lock set, ' + labelsPatched + ' label(s) -> placeholder, Gradle overrides ' + (at >= 0 ? 'refreshed' : 'appended') + (REMOVE_INTERNET_PERMISSION ? ', INTERNET permission removed' : ''));
